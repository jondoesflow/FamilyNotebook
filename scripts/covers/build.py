"""Render every cover to the asset catalog and regenerate CoverCatalog.swift.

    python3 scripts/covers/build.py   (needs node + playwright)
"""
import json, os, subprocess, sys, tempfile, shutil
sys.path.insert(0, os.path.dirname(__file__))
import art

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(ROOT, "FamilyNotebook/Resources/Assets.xcassets/Covers")
SWIFT = os.path.join(ROOT, "FamilyNotebook/Design/CoverCatalog.swift")
only = set(sys.argv[1:])

tmp = tempfile.mkdtemp()
jobs = []
for id_, cat, fn in art.COVERS:
    if only and id_ not in only: continue
    p = os.path.join(tmp, f"{id_}.svg")
    open(p, "w").write(art.svg(fn))
    jobs.append((id_, p))
json.dump(jobs, open(os.path.join(tmp, "jobs.json"), "w"))
subprocess.check_call(["node", os.path.join(os.path.dirname(__file__), "render.js"), os.path.join(tmp, "jobs.json"), tmp])

os.makedirs(ASSETS, exist_ok=True)
open(os.path.join(ASSETS, "Contents.json"), "w").write('{ "info" : { "author" : "xcode", "version" : 1 } }\n')
for id_, _ in jobs:
    d = os.path.join(ASSETS, f"cover-{id_}.imageset"); os.makedirs(d, exist_ok=True)
    shutil.copy(os.path.join(tmp, f"{id_}.jpg"), os.path.join(d, f"cover-{id_}.jpg"))
    json.dump({"images": [{"filename": f"cover-{id_}.jpg", "idiom": "universal"}], "info": {"author": "xcode", "version": 1}}, open(os.path.join(d, "Contents.json"), "w"), indent=1)

order = {c: i for i, c in enumerate(art.CATEGORY_ORDER)}
items = sorted([(c, i) for i, c, _ in art.COVERS], key=lambda t: order[t[0]])
lines = ["// Generated by scripts/covers/build.py. Do not edit.", "", "extension Cover {", "    static let illustrated: [Cover] = ["]
lines += [f'        Cover(id: "{i}", category: .{c}, art: .image("cover-{i}")),' for c, i in items]
lines += ["    ]", "}", ""]
open(SWIFT, "w").write("\n".join(lines))
print(f"{len(jobs)} covers rendered; tmp={tmp}")
